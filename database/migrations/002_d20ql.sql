CREATE TABLE IF NOT EXISTS d20_worlds (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 era VARCHAR(32) NOT NULL,
 seed VARCHAR(120) NOT NULL,
 width INT NOT NULL,
 height INT NOT NULL,
 turn_mode VARCHAR(32) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS d20_factions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 treasury BIGINT NOT NULL DEFAULT 0,
 population BIGINT NOT NULL DEFAULT 0,
 military BIGINT NOT NULL DEFAULT 0,
 research BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);